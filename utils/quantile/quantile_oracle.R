# Oracle data of sample quantiles for wadogo tests from R's quantile(type = 1..9).
# Run from the repository root: Rscript utils/quantile/quantile_oracle.R
# Writes test/resources/wadogo/r_quantiles.edn: {:data [...] :n n :type k :quantiles [...]},
# quantiles at the probabilities (1:(n-1))/n, as the inner quantiles of a :quantile scale with n range values.
set.seed(20261113)
num <- function(x) ifelse(x == round(x) & abs(x) < 1e15, sprintf("%.1f", x), sprintf("%.17g", x))
vec <- function(x) paste0("[", paste(num(x), collapse = " "), "]")
cases <- character(0)
datasets <- list(c(3, 6, 7, 8, 8, 10, 13, 15, 16, 20), c(1, 2), c(5, 5, 5, 1), 1:7)
for (i in 1:16) {
  m <- sample(3:40, 1)
  x <- round(rnorm(m, sample(c(-50, 0, 100), 1), runif(1, 0.1, 30)), sample(0:3, 1))
  datasets[[length(datasets) + 1]] <- x
}
for (x in datasets) {
  for (n in c(2, 3, 4, 5, 7)) {
    p <- (1:(n - 1)) / n
    for (type in 1:9) {
      q <- quantile(x, p, type = type, names = FALSE)
      cases <- c(cases, sprintf("{:data %s :n %d :type %d :quantiles %s}", vec(x), n, type, vec(q)))
    }
  }
}
writeLines(c(";; generated by utils/quantile/quantile_oracle.R, do not edit", "[", cases, "]"),
           "test/resources/wadogo/r_quantiles.edn")
cat(length(cases), "cases\n")
