## ---- datetime: pretty() on UTC POSIXct

dt <- function(x) format(x, "%Y-%m-%dT%H:%M:%OS6", tz = "UTC")
dts <- function(xs) if (!length(xs)) "[]" else paste0("[", paste0("\"", vapply(xs, function(x) dt(x), ""), "\"", collapse = " "), "]")

datetime_case <- function(start, end, n) {
  x <- c(start, end)
  p <- pretty(x, n = n)
  inside <- p[p >= start & p <= end]
  sprintf("{:start \"%s\" :end \"%s\" :n %d :pretty %s :inside %s}", dt(start), dt(end), n, dts(p), dts(inside))
}

