options(digits.secs = 6)
num <- function(x) sprintf("%.17g", x)
nums <- function(xs) paste0("[", paste(vapply(xs, num, ""), collapse = " "), "]")

## ---- linear: R_pretty spec and ticks inside the domain

linear_case <- function(lo, up, n, min.n = n %/% 3L) {
  z <- .pretty(c(lo, up), n = n, min.n = min.n, bounds = FALSE)
  p <- pretty(c(lo, up), n = n, min.n = min.n)
  ## ticks are the multiples ns..nu of unit, as drawn by R axes (GEPretty);
  ## pretty() itself returns seq(lo', up', length.out) which keeps unrounded ends
  ## when the first/last multiple is within the rounding tolerance
  m <- (z$ns:z$nu) * z$unit
  tol <- 1e-10 * z$unit
  inside <- m[m >= lo - tol & m <= up + tol]
  sprintf("{:lo %s :up %s :n %d :min-n %d :unit %s :ns %s :nu %s :pretty %s :inside %s}",
          num(lo), num(up), n, min.n, num(z$unit), num(z$ns), num(z$nu), nums(p), nums(inside))
}

