// Oracle data for wadogo tests from d3.
// Run from the repository root: (cd utils/d3 && npm install) && node utils/d3/d3_oracle.mjs
// Writes test/resources/wadogo/d3_log_ticks.edn and d3_linear_nice.edn
import { scaleLog, scaleLinear } from "d3-scale";
import { writeFileSync } from "node:fs";

// deterministic generator (mulberry32)
function rng(seed) {
  return () => {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rnd = rng(20261112);
const num = (x) => (Number.isInteger(x) ? x.toFixed(1) : String(x));
const vec = (xs) => "[" + xs.map(num).join(" ") + "]";
const header = ";; generated by utils/d3/d3_oracle.mjs, do not edit";

// ---- log ticks
// d3 uses one of: all subdivisions 1..base-1 of powers (integer base, fewer than n powers), powers of the base,
// or linear ticks when subdivisions are too few; the branch is recorded (wadogo uses the first two as candidate grids)
function branch(lo, hi, n, base) {
  const logs = (x) => Math.log(x) / Math.log(base);
  const i = logs(lo), j = logs(hi);
  if (base % 1 || !(j - i < n)) return "powers";
  // count subdivision ticks in the same way d3 does
  let c = 0;
  for (let e = Math.floor(i); e <= Math.ceil(j); ++e)
    for (let k = 1; k < base; ++k) {
      const t = e < 0 ? k / Math.pow(base, -e) : k * Math.pow(base, e);
      if (t >= lo && t <= hi) c++;
    }
  return c * 2 < n ? "fallback" : "subdivisions";
}

const logCases = [];
const addLog = (lo, hi, n, base) => {
  const neg = lo < 0;
  const [a, b] = neg ? [-hi, -lo] : [lo, hi];
  const br = branch(Math.min(a, b), Math.max(a, b), n, base);
  const ticks = scaleLog().base(base).domain([lo, hi]).ticks(n);
  logCases.push(`{:domain ${vec([lo, hi])} :n ${n} :base ${num(base)} :branch :${br} :ticks ${vec(ticks)}}`);
};
const edges = [[1, 1000, 5, 10], [1, 1000, 10, 10], [3, 7000, 5, 10], [1, 5, 5, 10], [6, 9, 5, 10], [2, 30, 5, 10],
               [1, 1e8, 5, 10], [1e-5, 1e5, 5, 10], [-1000, -1, 5, 10], [-1, -1000, 5, 10], [1000, 1, 5, 10],
               [1, 1024, 5, 2], [1, 1024, 20, 2], [0.01, 0.5, 5, 10], [1, 100, 5, Math.E], [1, 1e6, 5, Math.E],
               [1, 65536, 5, 16], [3, 200, 5, 16], [0.001, 0.002, 5, 10], [1, 1e30, 5, 10], [7, 8, 5, 10]];
for (const [lo, hi, n, b] of edges) addLog(lo, hi, n, b);
const bases = [2, Math.E, 10, 16];
for (let c = 0; c < 140; c++) {
  const base = bases[c % 4];
  const e0 = (rnd() - 0.5) * 12;
  const lo = Math.pow(10, e0) * (0.5 + rnd());
  const hi = lo * Math.pow(10, rnd() * 7);
  const n = 1 + Math.floor(rnd() * 12);
  const sign = rnd() < 0.15 ? -1 : 1;
  const rev = rnd() < 0.15;
  const d = rev ? [hi, lo] : [lo, hi];
  addLog(sign * d[0], sign * d[1], n, base);
}
writeFileSync("test/resources/wadogo/d3_log_ticks.edn", [header, "[", ...logCases, "]", ""].join("\n"));

// ---- linear nice
const niceCases = [];
const addNice = (a, b, n) => {
  const d = scaleLinear().domain([a, b]).nice(n).domain();
  niceCases.push(`{:domain ${vec([a, b])} :n ${n} :nice ${vec(d)}}`);
};
for (const [a, b, n] of [[0, 150, 10], [0.13, 0.97, 10], [-1, 2, 10], [3, 97, 5], [97, 3, 5], [-5, 5, 10],
                         [0.5, 0.6, 10], [1234, 1290, 10], [-0.37, 12.3, 3], [1e-9, 3e-9, 10], [0, 1e9, 7],
                         [1, 1.0000001, 10], [-130, -7, 4]])
  addNice(a, b, n);
for (let c = 0; c < 150; c++) {
  const a = (rnd() - 0.5) * Math.pow(10, rnd() * 12 - 4);
  const b = a + rnd() * Math.pow(10, rnd() * 12 - 4);
  const n = 1 + Math.floor(rnd() * 15);
  rnd() < 0.2 ? addNice(b, a, n) : addNice(a, b, n);
}
writeFileSync("test/resources/wadogo/d3_linear_nice.edn", [header, "[", ...niceCases, "]", ""].join("\n"));
