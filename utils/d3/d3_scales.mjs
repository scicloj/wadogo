// Oracle data of scale mappings for wadogo tests from d3-scale.
// Run from the repository root: (cd utils/d3 && npm install) && node utils/d3/d3_scales.mjs
// Writes test/resources/wadogo/d3_scales.edn: a vector of cases
//   {:id "..." :kind :linear :attrs {...wadogo attributes...} :forward [[x y] ...] :inverse [[y x] ...]}
// optional keys: :accessor (:lower - lower band edge of `(scale x true)`), :time? (values are UTC ISO datetimes)
import * as d3 from "d3-scale";
import { writeFileSync } from "node:fs";

// deterministic generator (mulberry32)
function rng(seed) {
  return () => {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rnd = rng(20261113);
const unif = (a, b) => a + (b - a) * rnd();
const pick = (xs) => xs[Math.floor(rnd() * xs.length)];

// EDN encoding
const edn = (x) => {
  if (x === undefined || x === null) return "nil";
  if (typeof x === "number") {
    if (Number.isNaN(x)) return "##NaN";
    if (!Number.isFinite(x)) return x > 0 ? "##Inf" : "##-Inf";
    return Number.isInteger(x) ? x.toFixed(1) : String(x);
  }
  if (typeof x === "boolean") return String(x);
  if (typeof x === "string") return JSON.stringify(x);
  if (x instanceof Date) return JSON.stringify(x.toISOString().replace("Z", ""));
  if (Array.isArray(x)) return "[" + x.map(edn).join(" ") + "]";
  if (x.kw) return ":" + x.kw;
  return "{" + Object.entries(x).map(([k, v]) => `:${k} ${edn(v)}`).join(" ") + "}";
};
const kw = (k) => ({ kw: k });
const header = ";; generated by utils/d3/d3_scales.mjs, do not edit";

const cases = [];
let counter = 0;
const add = (kind, attrs, scale, xs, ys, extra = {}) => {
  const c = { id: `${kind}-${counter++}`, kind: kw(kind), attrs, forward: xs.map((x) => [x, scale(x)]) };
  if (ys) c.inverse = ys.map((y) => [y, scale.invert(y)]);
  Object.assign(c, extra);
  cases.push(c);
};

// common setting variants: clamp, round, unknown
const settings = () => {
  const s = {};
  if (rnd() < 0.3) s.clamp = true;
  if (rnd() < 0.2) s.round = true;
  if (rnd() < 0.2) s.unknown = -1;
  return s;
};
const applySettings = (sc, s, rangeRound = true) => {
  if (s.clamp) sc.clamp(true);
  if (s.round && rangeRound) sc.rangeRound(sc.range());
  if (s.unknown !== undefined) sc.unknown(s.unknown);
  return sc;
};
// inputs: inside, outside, ends, missing values
const inputs = (a, b, n = 6) => {
  const lo = Math.min(a, b), hi = Math.max(a, b), w = hi - lo;
  const xs = [a, b, null, NaN];
  for (let i = 0; i < n; i++) xs.push(unif(lo - 0.3 * w, hi + 0.3 * w));
  return xs;
};
const rangeInputs = (r0, r1, n = 4) => {
  const lo = Math.min(r0, r1), hi = Math.max(r0, r1), w = hi - lo;
  const ys = [r0, r1];
  for (let i = 0; i < n; i++) ys.push(unif(lo - 0.2 * w, hi + 0.2 * w));
  return ys;
};
const randomRange = () => { const r0 = pick([0, -50, 100, unif(-10, 10)]); const r1 = r0 + pick([1, -1]) * unif(1, 500); return [r0, r1]; };

// ---- linear
for (let c = 0; c < 30; c++) {
  const a = unif(-1000, 1000), b = a + pick([1, -1]) * Math.pow(10, unif(-2, 3));
  const r = randomRange(), s = settings();
  const sc = applySettings(d3.scaleLinear().domain([a, b]).range(r), s);
  add("linear", { domain: [a, b], range: r, ...s }, sc, inputs(a, b), rangeInputs(r[0], r[1]));
}

// ---- identity (d3 has no clamp for identity)
for (let c = 0; c < 10; c++) {
  const a = unif(-100, 100), b = a + pick([1, -1]) * unif(1, 100);
  const s = rnd() < 0.3 ? { unknown: -1 } : {};
  const sc = d3.scaleIdentity().domain([a, b]);
  if (s.unknown !== undefined) sc.unknown(s.unknown);
  add("identity", { domain: [a, b], ...s }, sc, inputs(a, b), rangeInputs(a, b));
}

// ---- log
for (let c = 0; c < 30; c++) {
  const sign = rnd() < 0.25 ? -1 : 1;
  let a = Math.pow(10, unif(-3, 3)), b = a * Math.pow(10, unif(0.2, 5));
  if (rnd() < 0.2) [a, b] = [b, a];
  a *= sign; b *= sign;
  const r = randomRange(), s = settings();
  const sc = applySettings(d3.scaleLog().domain([a, b]).range(r), s);
  const lo = Math.min(Math.abs(a), Math.abs(b)), hi = Math.max(Math.abs(a), Math.abs(b));
  const xs = [a, b, null, NaN];
  for (let i = 0; i < 6; i++) xs.push(sign * Math.exp(unif(Math.log(lo) - 1, Math.log(hi) + 1)));
  add("log", { domain: [a, b], range: r, ...s }, sc, xs, rangeInputs(r[0], r[1]));
}

// ---- pow
for (let c = 0; c < 30; c++) {
  const e = pick([0.5, 2, 3, 1 / 3, 1, 1.7, 0.3]);
  const a = unif(-100, 100), b = a + pick([1, -1]) * unif(1, 200);
  const r = randomRange(), s = settings();
  const sc = applySettings(d3.scalePow().exponent(e).domain([a, b]).range(r), s);
  add("pow", { domain: [a, b], range: r, exponent: e, ...s }, sc, inputs(a, b), rangeInputs(r[0], r[1]));
}

// ---- symlog
for (let c = 0; c < 30; c++) {
  const C = pick([1, 1, 0.5, 10, 0.01]);
  const a = unif(-1e4, 1e3), b = a + pick([1, -1]) * Math.pow(10, unif(0, 4));
  const r = randomRange(), s = settings();
  const sc = applySettings(d3.scaleSymlog().constant(C).domain([a, b]).range(r), s);
  const attrs = { domain: [a, b], range: r, ...s };
  if (C !== 1) attrs.C = C;
  add("symlog", attrs, sc, inputs(a, b), rangeInputs(r[0], r[1]));
}

// ---- radial (round applies to the radius)
for (let c = 0; c < 20; c++) {
  const a = unif(0, 100), b = a + pick([1, -1]) * unif(1, 100);
  const r = [unif(0, 10), unif(20, 300)];
  if (rnd() < 0.2) r.reverse();
  const s = settings();
  const sc = d3.scaleRadial().domain([a, b]).range(r);
  if (s.clamp) sc.clamp(true);
  if (s.round) sc.round(true);
  if (s.unknown !== undefined) sc.unknown(s.unknown);
  add("radial", { domain: [a, b], range: r, ...s }, sc, inputs(a, b), rangeInputs(r[0], r[1]));
}

// ---- sequential (identity interpolator), forward only
const seqVariants = [
  ["linear", () => d3.scaleSequential(), () => { const a = unif(-100, 100); return [a, a + pick([1, -1]) * unif(1, 100)]; }, {}],
  ["log", () => d3.scaleSequentialLog(), () => { const a = Math.pow(10, unif(-2, 2)); return rnd() < 0.2 ? [a * 1000, a] : [a, a * Math.pow(10, unif(0.5, 4))]; }, {}],
  ["pow", () => d3.scaleSequentialPow().exponent(2), () => { const a = unif(-10, 10); return [a, a + unif(1, 50)]; }, { exponent: 2 }],
  ["pow", () => d3.scaleSequentialSqrt(), () => { const a = unif(0, 10); return [a, a + unif(1, 50)]; }, { exponent: 0.5 }],
  ["symlog", () => d3.scaleSequentialSymlog(), () => { const a = unif(-1000, 0); return [a, a + unif(1, 5000)]; }, {}],
  ["symlog", () => d3.scaleSequentialSymlog().constant(5), () => { const a = unif(-1000, 0); return [a, a + unif(1, 5000)]; }, { C: 5 }],
];
for (let c = 0; c < 30; c++) {
  const [transform, mk, dom, extra] = seqVariants[c % seqVariants.length];
  const d = dom();
  const sc = mk().domain(d);
  const s = {};
  if (rnd() < 0.3) { s.clamp = true; sc.clamp(true); }
  if (rnd() < 0.2) { s.unknown = -1; sc.unknown(-1); }
  const xs = transform === "log" ? [d[0], d[1], null, NaN, ...Array.from({ length: 6 }, () => Math.exp(unif(Math.log(Math.min(...d)) - 1, Math.log(Math.max(...d)) + 1)))] : inputs(d[0], d[1]);
  add("sequential", { domain: d, transform: kw(transform), ...extra, ...s }, sc, xs, null);
}

// ---- diverging (identity interpolator), forward only
const divVariants = [
  ["linear", () => d3.scaleDiverging(), () => { const m = unif(-10, 10); return [m - unif(1, 50), m, m + unif(1, 100)]; }, {}],
  ["linear", () => d3.scaleDiverging(), () => { const m = unif(-10, 10); return [m + unif(1, 50), m, m - unif(1, 100)]; }, {}],
  ["linear", () => d3.scaleDiverging(), () => { const m = unif(-10, 10); return [m, m, m + unif(1, 100)]; }, {}],
  ["log", () => d3.scaleDivergingLog(), () => { const m = Math.pow(10, unif(-1, 1)); return [m / unif(2, 100), m, m * unif(2, 1000)]; }, {}],
  ["pow", () => d3.scaleDivergingPow().exponent(2), () => { const m = unif(-10, 10); return [m - unif(1, 50), m, m + unif(1, 100)]; }, { exponent: 2 }],
  ["symlog", () => d3.scaleDivergingSymlog(), () => { const m = unif(-10, 10); return [m - unif(1, 500), m, m + unif(1, 1000)]; }, {}],
];
for (let c = 0; c < 30; c++) {
  const [transform, mk, dom, extra] = divVariants[c % divVariants.length];
  const d = dom();
  const sc = mk().domain(d);
  const s = {};
  if (rnd() < 0.3) { s.clamp = true; sc.clamp(true); }
  if (rnd() < 0.2) { s.unknown = -1; sc.unknown(-1); }
  const lo = Math.min(...d), hi = Math.max(...d);
  // d3 diverging maps null as 0 (no null check), wadogo returns :unknown; null isn't compared
  const xs = transform === "log" ? [...d, NaN, ...Array.from({ length: 6 }, () => Math.exp(unif(Math.log(lo) - 1, Math.log(hi) + 1)))] : [...d.slice(1), ...inputs(d[0], d[2]).filter((x) => x !== null)];
  add("diverging", { domain: d, transform: kw(transform), ...extra, ...s }, sc, xs, null);
}

// ---- quantize
for (let c = 0; c < 20; c++) {
  const a = unif(-100, 100), b = a + unif(0.5, 200);
  const n = 1 + Math.floor(rnd() * 8);
  const r = Array.from({ length: n }, (_, i) => i * 10);
  const sc = d3.scaleQuantize().domain([a, b]).range(r);
  const xs = [...sc.thresholds(), a, b, null, NaN];
  for (let i = 0; i < 6; i++) xs.push(unif(a - 20, b + 20));
  const s = rnd() < 0.3 ? { unknown: -1 } : {};
  if (s.unknown !== undefined) sc.unknown(-1);
  add("quantize", { domain: [a, b], range: r, ...s }, sc, xs, null);
}

// ---- quantile
for (let c = 0; c < 25; c++) {
  const m = 3 + Math.floor(rnd() * 30);
  const data = Array.from({ length: m }, () => Math.round(unif(-50, 50) * 100) / 100);
  if (rnd() < 0.3) data.push(data[0], data[1]);
  const n = 1 + Math.floor(rnd() * 6);
  const r = Array.from({ length: n }, (_, i) => i);
  const sc = d3.scaleQuantile().domain(data).range(r);
  const xs = [...sc.quantiles(), Math.min(...data), Math.max(...data), null, NaN, -1000, 1000];
  for (let i = 0; i < 6; i++) xs.push(unif(-60, 60));
  const s = rnd() < 0.3 ? { unknown: -1 } : {};
  if (s.unknown !== undefined) sc.unknown(-1);
  // values equal to a quantile are compared only when wadogo's quantile is the same double (see the test)
  add("quantile", { domain: data, range: r, ...s }, sc, xs, null, { quantiles: sc.quantiles() });
}

// ---- threshold
for (let c = 0; c < 15; c++) {
  const n = Math.floor(rnd() * 5);
  const t = Array.from({ length: n }, () => unif(-100, 100)).sort((a, b) => a - b);
  const r = Array.from({ length: n + 1 }, (_, i) => "abcdef"[i]);
  const sc = d3.scaleThreshold().domain(t).range(r);
  const xs = [...t, null, NaN, -1000, 1000];
  for (let i = 0; i < 6; i++) xs.push(unif(-120, 120));
  const s = rnd() < 0.3 ? { unknown: "?" } : {};
  if (s.unknown !== undefined) sc.unknown("?");
  add("threshold", { domain: t, range: r, ...s }, sc, xs, null);
}

// ---- bands (lower band edge and band width checked)
const letters = (n) => Array.from({ length: n }, (_, i) => "abcdefghij"[i]);
for (let c = 0; c < 40; c++) {
  const n = 1 + Math.floor(rnd() * 8);
  const r = randomRange();
  const pi = pick([0, 0.1, 0.3, 0.5, 1]), po = pick([0, 0.2, 0.5, 1, 2]), al = pick([0, 0.25, 0.5, 1]);
  const round = rnd() < 0.3;
  const sc = d3.scaleBand().domain(letters(n)).range(r).paddingInner(pi).paddingOuter(po).align(al).round(round);
  const attrs = { domain: letters(n), range: r, "padding-in": pi, "padding-out": po, "align-outer": al };
  if (round) attrs.round = true;
  add("bands", attrs, sc, [...letters(n), "z", null], null, { accessor: kw("lower"), bandwidth: sc.bandwidth(), step: sc.step() });
}

// ---- point
for (let c = 0; c < 20; c++) {
  const n = 1 + Math.floor(rnd() * 8);
  const r = randomRange();
  const p = pick([0, 0.5, 1, 2]), al = pick([0, 0.25, 0.5, 1]);
  const round = rnd() < 0.3;
  const sc = d3.scalePoint().domain(letters(n)).range(r).padding(p).align(al).round(round);
  const attrs = { domain: letters(n), range: r, padding: p, "align-outer": al };
  if (round) attrs.round = true;
  add("point", attrs, sc, [...letters(n), "z", null], null, { step: sc.step() });
}

// ---- ordinal (range cycling; d3's implicit domain growth is disabled by an explicit unknown)
for (let c = 0; c < 10; c++) {
  const n = 1 + Math.floor(rnd() * 8), m = 1 + Math.floor(rnd() * 5);
  const r = Array.from({ length: m }, (_, i) => i * 1.5);
  const sc = d3.scaleOrdinal().domain(letters(n)).range(r).unknown(null);
  add("ordinal", { domain: letters(n), range: r }, sc, [...letters(n), "z"], null);
}

// ---- time (UTC)
const utc = (ms) => new Date(Math.round(ms));
for (let c = 0; c < 20; c++) {
  const t0 = Date.UTC(1990, 0, 1) + unif(0, 40 * 365.25 * 864e5);
  const t1 = t0 + pick([1, -1]) * Math.pow(10, unif(4, 10.5));
  const r = randomRange();
  const s = settings();
  const sc = applySettings(d3.scaleUtc().domain([utc(t0), utc(t1)]).range(r), s);
  const xs = [utc(t0), utc(t1), null];
  for (let i = 0; i < 5; i++) xs.push(utc(unif(Math.min(t0, t1) - 0.3 * Math.abs(t1 - t0), Math.max(t0, t1) + 0.3 * Math.abs(t1 - t0))));
  const ys = rangeInputs(r[0], r[1]);
  add("datetime", { domain: [utc(t0), utc(t1)], range: r, ...s }, sc, xs, ys, { "time?": true });
}

writeFileSync("test/resources/wadogo/d3_scales.edn", [header, "[", ...cases.map(edn), "]", ""].join("\n"));
console.log(`${cases.length} cases`);
